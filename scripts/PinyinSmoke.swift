import Foundation

@main
struct PinyinSmoke {
    static func main() throws {
        let data = try Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1]))
        let lexicon = try JSONDecoder().decode([String: [String]].self, from: data)
        let engine = PinyinEngine(lexicon: lexicon)
        precondition(engine.candidates(for: "nihao").first?.text == "你好")
        precondition(engine.candidates(for: "zhongwen").first?.text == "中文")
        precondition(engine.candidates(for: "ceshi").first?.text == "测试")
        precondition(engine.candidates(for: "zhongguo").first?.text == "中国")
        let fixture = PinyinEngine(lexicon: ["nihao": ["你好"], "ma": ["吗"], "xing": ["行", "星"]])
        precondition(fixture.candidates(for: "nihaoma").first == PinyinCandidate(text: "你好吗", consumed: 7))
        precondition(fixture.candidates(for: "xing").count == 2)
        precondition(fixture.candidates(for: "xi").first?.consumed == 2)
        precondition(fixture.candidates(for: "").isEmpty)
        precondition(engine.candidates(for: "wo").first == PinyinCandidate(text: "我", consumed: 2))
        precondition(engine.candidates(for: "wom").first == PinyinCandidate(text: "我们", consumed: 3))
        precondition(engine.candidates(for: "wome").first == PinyinCandidate(text: "我们", consumed: 4))
        precondition(engine.candidates(for: "women").first == PinyinCandidate(text: "我们", consumed: 5))
        precondition(engine.candidates(for: "WOM").first?.text == "我们")
        let mixed = PinyinEngine(lexicon: ["wo": ["我"], "women": ["我们"], "zhongguo": ["中国"], "zhong": ["中"]])
        precondition(mixed.candidates(for: "wom").first?.consumed == 3)
        precondition(mixed.candidates(for: "zhongg").first == PinyinCandidate(text: "中国", consumed: 6))
        precondition(mixed.candidates(for: "wog").first == PinyinCandidate(text: "我", consumed: 2))
        precondition(mixed.candidates(for: "woaini").first?.consumed == 2)
        precondition(mixed.candidates(for: String(repeating: "a", count: 65)).isEmpty)
        let wom = engine.candidates(for: "wom")
        precondition(wom.contains { $0.text == "我妈" && $0.consumed == 3 })
        precondition(wom.contains { $0.text == "我没" && $0.consumed == 3 })
        precondition(wom.filter { $0.consumed == 3 }.count >= 5)
        precondition(engine.candidates(for: "nihaom").first == PinyinCandidate(text: "你好吗", consumed: 6))
        precondition(engine.candidates(for: "nihaoma").first?.text == "你好吗")
        precondition(engine.candidates(for: "nihaom").contains { $0.text == "你好妈" && $0.consumed == 6 })
        precondition(engine.candidates(for: "woaini").contains { $0.text == "我爱你" && $0.consumed == 6 })
        let sentence = engine.candidates(for: "womendouyouyigejia")
        precondition(sentence.contains { $0.text == "我们都有一个家" && $0.consumed == 18 })
        precondition(sentence.contains { $0.text == "我们" && $0.consumed == 5 })
        precondition(engine.candidates(for: "wom").count <= 40)
        print("Pinyin smoke: 28 checks passed; bundled keys: \(lexicon.count)")
    }
}
